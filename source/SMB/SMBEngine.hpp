/**
 * @file
 * @brief The engine that runs the translated Super Mario Bros. code.
 */
#ifndef SMBENGINE_HPP
#define SMBENGINE_HPP

#include <array>
#include <cstddef>
#include <cstdint>
#include <memory>
#include <vector>

#include "../Emulation/Controller.hpp"
#include "../Emulation/MemoryAccess.hpp"
#include "../Emulation/Palette.hpp"

class APU;
class PPU;

/**
 * Engine that runs Super Mario Bros.
 * Emulates the parts of the NES that the translated code still relies on.
 */
class SMBEngine : private StatusFlags
{
public:
    /**
     * Number of bytes of CHR (graphics) data the engine expects.
     */
    static constexpr std::size_t CHR_SIZE = 0x2000;

    /**
     * @param chr CHR_SIZE bytes of graphics data from the Super Mario Bros. ROM image.
     * @param audioSampleRate the audio sample rate in Hz, or 0 to disable audio.
     * @param frameRate the number of times update() is called per second.
     */
    SMBEngine(const uint8_t* chr, int audioSampleRate, int frameRate);

    ~SMBEngine();

    SMBEngine(const SMBEngine&) = delete;
    SMBEngine& operator=(const SMBEngine&) = delete;

    /**
     * Get the controller for player 1 (0) or player 2 (1).
     */
    Controller& getController(int player);

    /**
     * Audio samples generated by the last update().
     */
    const std::vector<int16_t>& getAudioSamples() const;

    /**
     * The 2 KiB of work RAM.
     */
    const std::array<uint8_t, 0x800>& getRam() const;

    /**
     * Render the screen to a buffer.
     *
     * @param buffer a 256x240 buffer of ARGB pixels.
     */
    void render(uint32_t* buffer) const;

    /**
     * Reset the game engine, like pressing the console's reset button.
     */
    void reset();

    /**
     * Set the colors used for rendering.
     */
    void setPalette(const Palette& palette);

    /**
     * Update the game engine by one frame.
     */
    void update();

private:
    // NES emulation subsystems
    std::unique_ptr<APU> apu;
    std::unique_ptr<PPU> ppu;
    std::array<Controller, 2> controllers;
    bool audioEnabled;
    Palette palette = DEFAULT_PALETTE;

    // NES CPU state
    uint8_t registerA = 0;
    uint8_t registerX = 0;
    uint8_t registerY = 0;
    uint8_t registerS = 0;
    MemoryAccess a{*this, &registerA}; /**< Accumulator. */
    MemoryAccess x{*this, &registerX}; /**< X index register. */
    MemoryAccess y{*this, &registerY}; /**< Y index register. */
    MemoryAccess s{*this, &registerS}; /**< Stack pointer. */
    std::array<uint8_t, 0x8000> dataStorage{}; /**< Constant data from the ROM, mapped at $8000. */
    std::array<uint8_t, 0x800> ram{};           /**< 2 KiB of work RAM. */
    std::array<int, 100> returnIndexStack{};    /**< Return points of active JSR subroutine calls. */
    int returnIndexStackTop = 0;

    /**
     * Run the translated code for the game (see SMB.cpp).
     *
     * @param mode 0 runs the initialization routine, 1 runs the logic for one frame.
     */
    void code(int mode);

    /**
     * Copy the constant data from the ROM into the address space (see SMBData.cpp).
     */
    void loadConstantData();

    /**
     * Map constant data into the address space at or above $8000.
     */
    void writeData(uint16_t address, const uint8_t* data, std::size_t length);

    uint8_t readIO(uint16_t address);
    void writeIO(uint16_t address, uint8_t value);

    //---------------------------------------------------------------------
    // Operations used by the translated code. These are defined inline
    // since they are executed very frequently.
    //---------------------------------------------------------------------

    /**
     * Get a memory access object for a particular address.
     */
    MemoryAccess getMemory(uint16_t address)
    {
        if (address >= 0x8000)
        {
            return MemoryAccess(*this, &dataStorage[address - 0x8000]);
        }
        if (address < 0x2000)
        {
            return MemoryAccess(*this, &ram[address & 0x7ff]);
        }
        return MemoryAccess(*this, readIO(address));
    }

    /**
     * Get a little-endian word from the zero page.
     */
    uint16_t getMemoryWord(uint8_t address)
    {
        return static_cast<uint16_t>(readData(address) | (readData(static_cast<uint8_t>(address + 1)) << 8));
    }

    /**
     * Read data from an address in the NES address space.
     */
    uint8_t readData(uint16_t address)
    {
        if (address >= 0x8000)
        {
            return dataStorage[address - 0x8000];
        }
        if (address < 0x2000)
        {
            return ram[address & 0x7ff];
        }
        return readIO(address);
    }

    /**
     * Write data to an address in the NES address space.
     */
    void writeData(uint16_t address, uint8_t value)
    {
        if (address < 0x2000)
        {
            ram[address & 0x7ff] = value;
        }
        else
        {
            writeIO(address, value);
        }
    }

    /**
     * CMP, CPX and CPY instructions.
     */
    void compare(uint8_t value1, uint8_t value2)
    {
        c = (value1 >= value2);
        setZN(static_cast<uint8_t>(value1 - value2));
    }

    /**
     * BIT instruction.
     */
    void bit(uint8_t value)
    {
        n = (value & 0x80) != 0;
        z = (registerA & value) == 0;
    }

    /**
     * PHA instruction.
     */
    void pha()
    {
        writeData(0x100 | registerS, registerA);
        registerS--;
    }

    /**
     * PLA instruction.
     */
    void pla()
    {
        registerS++;
        a = readData(0x100 | registerS);
    }

    /**
     * Push the return point of a JSR.
     */
    void pushReturnIndex(int index)
    {
        returnIndexStack[++returnIndexStackTop] = index;
    }

    /**
     * Pop the return point for an RTS.
     */
    int popReturnIndex()
    {
        return returnIndexStack[returnIndexStackTop--];
    }
};

#endif // SMBENGINE_HPP
