/**
 * @file
 * @brief Audio Processing Unit emulation.
 */
#ifndef APU_HPP
#define APU_HPP

#include <cstdint>
#include <memory>
#include <vector>

class Pulse;
class Triangle;
class Noise;
class OutputFilter;

/**
 * Emulates the pulse, triangle and noise channels of the NES Audio Processing Unit,
 * including the console's nonlinear mixer and analog output filters.
 */
class APU
{
public:
    /**
     * @param sampleRate the output sample rate, in Hz.
     * @param frameRate the number of frames generated per second.
     */
    APU(int sampleRate, int frameRate);
    ~APU();

    /**
     * Generate one frame of audio, replacing the previous frame's samples.
     */
    void stepFrame();

    /**
     * Signed 16-bit mono samples generated by the last call to stepFrame().
     */
    const std::vector<int16_t>& getSamples() const;

    void writeRegister(uint16_t address, uint8_t value);

private:
    int sampleRate;
    int frameRate;
    int frameValue = 0; /**< The value of the frame counter. */
    std::vector<int16_t> samples;

    std::unique_ptr<Pulse> pulse1;
    std::unique_ptr<Pulse> pulse2;
    std::unique_ptr<Triangle> triangle;
    std::unique_ptr<Noise> noise;
    std::unique_ptr<OutputFilter> filter;

    int getOutput() const;
    void stepEnvelope();
    void stepSweep();
    void stepLength();
    void writeControl(uint8_t value);
};

#endif // APU_HPP
